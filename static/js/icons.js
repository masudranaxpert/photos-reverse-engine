/**
 * Build an inline SVG icon string.
 * @param {string} name - key inside ICONS
 * @param {number|string} [size=18] - pixel size
 * @param {string} [cls=""] - extra CSS classes
 */
function icon(name, size = 18, cls = "") {
  const paths = ICONS[name];
  if (!paths) return "";
  return (
    `<svg class="icon ${cls}" width="${size}" height="${size}" viewBox="0 0 24 24" fill="none"` +
    ` stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">` +
    paths +
    `</svg>`
  );
}

/**
 * Replace every <span data-icon="name" data-size="18"></span> in the
 * document (or a root element) with its SVG. Safe to call repeatedly.
 */
function hydrateIcons(root = document) {
  root.querySelectorAll("[data-icon]").forEach((el) => {
    const name = el.getAttribute("data-icon");
    const size = el.getAttribute("data-size") || 18;
    el.innerHTML = icon(name, size);
    el.removeAttribute("data-icon");
    el.removeAttribute("data-size");
  });
}

window.hydrateIcons = hydrateIcons;
window.renderIcons = hydrateIcons;

document.addEventListener("DOMContentLoaded", () => hydrateIcons());
